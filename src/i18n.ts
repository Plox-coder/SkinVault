const dict: Record<Language, Record<keyof typeof es, string>> = { es, en, ca };
export type TranslationKey = keyof typeof es;

export function createTranslator(language: Language) {
  return (key: TranslationKey, variables: Record<string, string | number> = {}) =>
    dict[language][key].replace(/\{(\w+)\}/g, (_, placeholder: string) => String(variables[placeholder] ?? `{${placeholder}}`));
}

export function initialLanguage(): Language {
  try {
    const saved = localStorage.getItem(LANGUAGE_STORAGE_KEY);
    if (saved === 'es' || saved === 'en' || saved === 'ca') return saved;
  } catch { /* e.g. private mode */ }
  // New visitors start in English; an explicitly selected language is preserved.
  return 'en';
}
